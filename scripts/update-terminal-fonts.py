#!/usr/bin/env python3
"""Refresh pinned, full-coverage WOFF2 assets (requires fonttools[woff])."""
import hashlib, io, json, pathlib, tarfile, urllib.parse, subprocess
from fontTools.ttLib import TTFont
ROOT = pathlib.Path(__file__).resolve().parents[1] / 'js/packages/terminal-core'
REV = '5bb28733cec313b63fbd415b574b5ae35c8aa8b8'
BASE = f'https://raw.githubusercontent.com/google/fonts/{REV}/ofl/'
FAMILIES = [
 ('source-code-pro','Source Code Pro','sourcecodepro','SourceCodePro'),
 ('jetbrains-mono','JetBrains Mono','jetbrainsmono','JetBrainsMono'),
 ('fira-code','Fira Code','firacode','FiraCode'),
 ('cascadia-code','Cascadia Code','cascadiacode','CascadiaCode'),
]
def download(url):
    print('Fetching',url,flush=True)
    return subprocess.check_output(['curl','-fLsS','--max-time','45','--retry','2',url])
def emit(identifier, family, data, style, source):
    font = TTFont(io.BytesIO(data), recalcTimestamp=False)
    weight = next((f'{a.minValue:g} {a.maxValue:g}' for a in font['fvar'].axes if a.axisTag == 'wght'), '400') if 'fvar' in font else str(font['OS/2'].usWeightClass)
    font.flavor = 'woff2'
    output = io.BytesIO(); font.save(output); payload = output.getvalue()
    digest = hashlib.sha256(payload).hexdigest()
    name = f'{identifier}-{style}-{weight.replace(" ", "_")}-{digest[:16]}.woff2'
    (ROOT / 'fonts' / name).write_bytes(payload)
    return {'file':name, 'style':style, 'weight':weight, 'bytes':len(payload), 'sha256':digest, 'source':source, 'sourceSha256':hashlib.sha256(data).hexdigest()}
(ROOT/'fonts').mkdir(exist_ok=True)
(ROOT/'font-licenses').mkdir(exist_ok=True)
manifest=[]
for identifier, family, folder, stem in FAMILIES:
    files=[]
    for style, filename in [('normal',stem+'[wght].ttf'), ('italic',stem+'-Italic[wght].ttf')]:
        if identifier == 'fira-code' and style == 'italic': continue
        url=BASE+folder+'/'+urllib.parse.quote(filename)
        files.append(emit(identifier,family,download(url),style,url))
    (ROOT/'font-licenses'/f'{identifier}.txt').write_bytes(download(BASE+folder+'/OFL.txt'))
    manifest.append({'id':identifier,'name':family,'files':files})
url='https://github.com/dejavu-fonts/dejavu-fonts/releases/download/version_2_37/dejavu-fonts-ttf-2.37.tar.bz2'
archive=tarfile.open(fileobj=io.BytesIO(download(url)),mode='r:bz2')
files=[]
for suffix,style in [('', 'normal'),('-Bold','normal'),('-Oblique','italic'),('-BoldOblique','italic')]:
    name='dejavu-fonts-ttf-2.37/ttf/DejaVuSansMono'+suffix+'.ttf'
    files.append(emit('dejavu-sans-mono','DejaVu Sans Mono',archive.extractfile(name).read(),style,url+'#'+name))
(ROOT/'font-licenses/dejavu-sans-mono.txt').write_bytes(archive.extractfile('dejavu-fonts-ttf-2.37/LICENSE').read())
manifest.insert(0,{'id':'dejavu-sans-mono','name':'DejaVu Sans Mono','files':files})
(ROOT/'font-manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
lines=['// Generated by scripts/update-terminal-fonts.py; URLs are resolved by both bundlers.', 'export const FONT_FILES: Record<string, string> = {']
for item in manifest:
    for f in item['files']:
        lines.append(f'    "{f["file"]}": new URL("./fonts/{f["file"]}", import.meta.url).href,')
lines.append('};\n')
(ROOT/'font-files.ts').write_text('\n'.join(lines))
print('Packaged',sum(len(f['files']) for f in manifest),'font files,',sum(x['bytes'] for f in manifest for x in f['files']),'bytes')
