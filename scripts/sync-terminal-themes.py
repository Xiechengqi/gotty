#!/usr/bin/env python3
"""Generate the npm theme catalogue from the server's canonical embedded JSON."""
import json,pathlib
root=pathlib.Path(__file__).resolve().parents[1]
data=json.loads((root/'server/terminaldata/themes.json').read_text())
(root/'js/packages/terminal-core/themes.ts').write_text('// Generated by scripts/sync-terminal-themes.py.\nexport const BUILTIN_THEMES: Record<string, Record<string, string>> = '+json.dumps(data,indent=2)+';\n')
